CREATE DATABASE IF NOT EXISTS `db`
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_general_ci;

USE `db`;

-- 1. ADMIN ACCOUNTS
CREATE TABLE IF NOT EXISTS `users` (
  `id` INT(11) NOT NULL AUTO_INCREMENT,
  `name` VARCHAR(100) NOT NULL,
  `email` VARCHAR(255) NOT NULL,
  `password_hash` VARCHAR(255) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_users_email` (`email`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- 2. FACILITIES
CREATE TABLE IF NOT EXISTS `facility` (
  `id` INT(11) NOT NULL AUTO_INCREMENT,
  `name` VARCHAR(100) NOT NULL,
  `capacity` INT(11) NOT NULL,
  `open_time` TIME NOT NULL,
  `close_time` TIME NOT NULL,
  `is_active` TINYINT(1) NOT NULL DEFAULT 1,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- Schedules
CREATE TABLE schedules (
    id INT AUTO_INCREMENT PRIMARY KEY,
    sarf_id INT NOT NULL UNIQUE,
    facility_id INT NOT NULL,
    event_title VARCHAR(255) NOT NULL,
    start_datetime DATETIME NOT NULL,
    end_datetime DATETIME NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'scheduled',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    INDEX (facility_id),
    INDEX (start_datetime, end_datetime)
);


-- 3. SARF TRACKING AND DECISIONS
CREATE TABLE IF NOT EXISTS `sarf` (
  `id` INT(11) NOT NULL AUTO_INCREMENT,
  `admin_id` INT(11) NULL DEFAULT NULL,
  `control_number` VARCHAR(20) NOT NULL,
  `status` ENUM('pending', 'approved', 'rejected') NOT NULL DEFAULT 'pending',
  `reject_reason` TEXT NULL,
  `scan_path` VARCHAR(255) NULL,
  `decided_at` DATETIME NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_sarf_control_number` (`control_number`),
  KEY `idx_sarf_admin` (`admin_id`),
  KEY `idx_sarf_status_created` (`status`, `created_at`),
  CONSTRAINT `fk_sarf_admin` FOREIGN KEY (`admin_id`)
    REFERENCES `users` (`id`) ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- 4. SARF REQUEST DETAILS (ONE DETAIL RECORD PER SARF)
CREATE TABLE IF NOT EXISTS `sarf_req` (
  `id` INT(11) NOT NULL AUTO_INCREMENT,
  `sarf_id` INT(11) NOT NULL,
  `facility_id` INT(11) NOT NULL,
  `type_of_activity` VARCHAR(100) NOT NULL,
  `name_of_organizer_office_college` VARCHAR(150) NOT NULL,
  `name_of_program` VARCHAR(200) NOT NULL,
  `nature_of_activity` VARCHAR(150) NOT NULL,
  `start_datetime` DATETIME NOT NULL,
  `end_datetime` DATETIME NOT NULL,
  `participants_type` VARCHAR(100) NOT NULL,
  `est_total_participants` INT(11) NOT NULL,
  `in_charge_name` VARCHAR(100) NOT NULL,
  `in_charge_designation` VARCHAR(100) NOT NULL,
  `in_charge_contact` VARCHAR(30) NOT NULL,
  `in_charge_email` VARCHAR(100) NOT NULL,
  `source_of_budget` VARCHAR(150) NULL,
  `estimated_total_budget` DECIMAL(12,2) NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_sarf_req_sarf` (`sarf_id`),
  KEY `idx_sarf_req_facility` (`facility_id`),
  KEY `idx_sarf_req_start` (`start_datetime`),
  KEY `idx_sarf_req_end` (`end_datetime`),
  CONSTRAINT `fk_sarf_req_sarf` FOREIGN KEY (`sarf_id`)
    REFERENCES `sarf` (`id`) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT `fk_sarf_req_facility` FOREIGN KEY (`facility_id`)
    REFERENCES `facility` (`id`) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

