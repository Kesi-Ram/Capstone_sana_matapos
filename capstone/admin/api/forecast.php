
<?php
require_once __DIR__ . "/db.php";
session_start();

header("Content-Type: application/json; charset=utf-8");

// Only logged-in FMO admins can access the forecasts.
if (!isset($_SESSION["user_id"])) {
    http_response_code(401);

    echo json_encode([
        "message" => "Please log in first."
    ]);

    exit;
}

// Retrieve the actual facility names from MySQL.
$stmt = $pdo->prepare("SELECT id, name FROM facility");
$stmt->execute();

$facilities = $stmt->fetchAll(PDO::FETCH_ASSOC);

// Store each facility name using its ID.
$facilityNames = [];

foreach ($facilities as $facility) {
    $facilityNames[$facility["id"]] = $facility["name"];
}

// Find the main Capstone folder.
$projectFolder = dirname(__DIR__, 2);

// Locate the CSV generated by predict.py.
$filePath = $projectFolder . "/ml/forecasts/monthly_demand_forecast.csv";

// Check whether the forecast file exists.
if (!file_exists($filePath)) {
    http_response_code(404);

    echo json_encode([
        "message" => "Forecast data not found. Run predict.py first."
    ]);

    exit;
}

// Open the CSV file.
$file = fopen($filePath, "r");

if ($file === false) {
    http_response_code(500);

    echo json_encode([
        "message" => "Could not read forecast data."
    ]);

    exit;
}

// Read the CSV column names.
$headers = fgetcsv($file);

$forecasts = [];

// Read each prediction.
while (($row = fgetcsv($file)) !== false) {

    if ($headers === false || count($row) !== count($headers)) {
        continue;
    }

    // Match the CSV values to their column names.
    $data = array_combine($headers, $row);


$facilityId = (int)$data["facility_id"];

$forecasts[] = [
    "facility_id" => $facilityId,

    // Get the facility name from MySQL.
    "facility_name" => $facilityNames[$facilityId] ?? null,

    "year" => (int)$data["year"],
    "month" => (int)$data["month"],
    "predicted_requests" => (int)$data["predicted_requests"]
];

}

fclose($file);

// Send the predictions to React as JSON.
echo json_encode([
    "source" => "synthetic",
    "forecasts" => $forecasts
]);
